-- =====================================================================
-- TrucoClub - esquema de la base de datos para Supabase (PostgreSQL)
-- Pegalo entero en Supabase -> SQL Editor -> New query -> Run.
-- Los nombres de tablas y columnas son los que espera Spring/Hibernate,
-- así el backend funciona sin cambiar las entidades.
--
-- Las tablas van en el esquema "trucoclub" (no en "public"): Supabase
-- publica "public" en su API REST, y esta base solo la usa el backend.
-- =====================================================================

create schema if not exists trucoclub;

-- ---------------------------------------------------------------------
-- usuarios: perfil de jugador de cada cuenta de Supabase Auth (auth.users).
-- El login, el email y la contraseña los maneja Supabase Auth; acá va lo del juego.
-- ---------------------------------------------------------------------
create table if not exists trucoclub.usuarios (
    id               bigint generated by default as identity primary key,
    auth_id          uuid           unique references auth.users (id),  -- el usuario de Supabase Auth
    username         varchar(255)   not null unique,
    email            varchar(255)   not null unique,        -- copia del email de auth.users
    dni              varchar(8),                            -- solo números; para verificar pagos y retiros
    fecha_registro   timestamp(6),
    partidas_ganadas integer        default 0,
    saldo            numeric(14, 2) default 0,
    foto_url         varchar(255),
    rol              varchar(20)    default 'JUGADOR',      -- JUGADOR | ADMIN
    bloqueado        boolean        default false,          -- cuenta suspendida
    motivo_bloqueo   varchar(200)
);

-- ---------------------------------------------------------------------
-- historial_partidas: resultado de cada partido terminado
-- ---------------------------------------------------------------------
create table if not exists trucoclub.historial_partidas (
    id              bigint generated by default as identity primary key,
    fecha_jugada    timestamp(6),
    ganador_id      bigint not null references trucoclub.usuarios (id),
    perdedor_id     bigint not null references trucoclub.usuarios (id),
    puntos_ganador  integer,
    puntos_perdedor integer
);

-- ---------------------------------------------------------------------
-- mesas: cada mesa con plata (dónde está la plata en todo momento)
-- ---------------------------------------------------------------------
create table if not exists trucoclub.mesas (
    id         bigint generated by default as identity primary key,
    creador_id bigint         not null references trucoclub.usuarios (id),
    rival_id   bigint                  references trucoclub.usuarios (id),
    monto      numeric(14, 2) not null,                     -- lo que pone cada jugador
    puntos     integer        not null,                     -- 15 o 30
    estado     varchar(20)    not null,                     -- ESPERANDO | JUGANDO | TERMINADA | CANCELADA | ANULADA
    ganador    varchar(50),                                 -- nombre que tenía al ganar
    ganador_id bigint                  references trucoclub.usuarios (id),
    premio     numeric(14, 2),                              -- monto x 2 - 5%
    comision   numeric(14, 2),                              -- lo que se queda el sitio
    creada     timestamp(6)   not null,
    terminada  timestamp(6)
);

-- ---------------------------------------------------------------------
-- movimientos: depósitos, retiros, apuestas, premios y devoluciones
-- ---------------------------------------------------------------------
create table if not exists trucoclub.movimientos (
    id             bigint generated by default as identity primary key,
    usuario_id     bigint         not null references trucoclub.usuarios (id),
    tipo           varchar(20)    not null,                 -- DEPOSITO | RETIRO | APUESTA | PREMIO | DEVOLUCION
    estado         varchar(20)    not null,                 -- PENDIENTE | APROBADO | RECHAZADO | CANCELADO
    monto          numeric(14, 2) not null,
    detalle        varchar(60)    not null,                 -- nro. de operación, alias/CBU o texto de la mesa
    saldo_despues  numeric(14, 2),
    motivo_rechazo varchar(200),
    creado         timestamp(6)   not null,
    resuelto       timestamp(6),
    resuelto_por   varchar(50)                              -- admin que lo aprobó o rechazó
);

-- ---------------------------------------------------------------------
-- notificaciones: avisos de la campanita
-- ---------------------------------------------------------------------
create table if not exists trucoclub.notificaciones (
    id         bigint generated by default as identity primary key,
    usuario_id bigint       not null references trucoclub.usuarios (id),
    tipo       varchar(20)  not null,                       -- OK | ERROR | PREMIO | INFO
    texto      varchar(300) not null,
    leida      boolean      not null default false,
    creada     timestamp(6) not null
);

-- ---------------------------------------------------------------------
-- Índices para las búsquedas que hace el backend
-- ---------------------------------------------------------------------
create unique index if not exists usuarios_dni_unico on trucoclub.usuarios (dni) where dni is not null;
create unique index if not exists usuarios_username_minusculas on trucoclub.usuarios (lower(username));
create index if not exists idx_movimientos_usuario   on trucoclub.movimientos (usuario_id, id desc);
create index if not exists idx_movimientos_estado    on trucoclub.movimientos (estado, tipo);
create index if not exists idx_mesas_estado          on trucoclub.mesas (estado);
create index if not exists idx_mesas_terminada       on trucoclub.mesas (estado, terminada);
create index if not exists idx_mesas_creador         on trucoclub.mesas (creador_id);
create index if not exists idx_mesas_rival           on trucoclub.mesas (rival_id);
create index if not exists idx_notificaciones_usuario on trucoclub.notificaciones (usuario_id, leida);
create index if not exists idx_historial_ganador     on trucoclub.historial_partidas (ganador_id);
create index if not exists idx_historial_perdedor    on trucoclub.historial_partidas (perdedor_id);

-- ---------------------------------------------------------------------
-- Seguridad extra: aunque el esquema no está publicado en la API, activamos
-- RLS sin políticas. El backend entra con el usuario dueño de las tablas
-- (postgres), que no se ve afectado; cualquier otro rol no ve nada.
-- ---------------------------------------------------------------------
alter table trucoclub.usuarios           enable row level security;
alter table trucoclub.historial_partidas enable row level security;
alter table trucoclub.mesas              enable row level security;
alter table trucoclub.movimientos        enable row level security;
alter table trucoclub.notificaciones     enable row level security;

-- Que los roles de la API de Supabase no tengan acceso a este esquema
revoke all on schema trucoclub from anon, authenticated;

-- ---------------------------------------------------------------------
-- Supabase Auth -> perfil de TrucoClub
-- Al registrarse (supabase.auth.signUp con options.data.username y options.data.dni)
-- se crea solo el perfil. Si el nombre o el DNI son inválidos o ya existen, el registro falla.
-- Con Google no viene nombre ni DNI: la cuenta se crea igual y el perfil lo crea el backend
-- cuando el jugador elige su nombre (POST /api/auth/completar-perfil). El DNI se pide al depositar/retirar.
-- ---------------------------------------------------------------------
create or replace function trucoclub.crear_perfil_de_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    nombre text := trim(coalesce(new.raw_user_meta_data ->> 'username', ''));
    documento text := regexp_replace(coalesce(new.raw_user_meta_data ->> 'dni', ''), '[^0-9]', '', 'g');
    proveedor text := coalesce(new.raw_app_meta_data ->> 'provider', 'email');
begin
    if proveedor <> 'email' and nombre = '' then
        return new;
    end if;

    if nombre !~ '^[A-Za-z0-9_.]{3,20}$' then
        raise exception 'NOMBRE_INVALIDO: el nombre tiene que tener de 3 a 20 caracteres (letras, números, _ o punto)';
    end if;
    if exists (select 1 from trucoclub.usuarios u where lower(u.username) = lower(nombre)) then
        raise exception 'NOMBRE_OCUPADO: ese nombre ya lo usa otro jugador';
    end if;
    if documento !~ '^[0-9]{7,8}$' then
        raise exception 'DNI_INVALIDO: el DNI tiene que tener 7 u 8 números';
    end if;
    if exists (select 1 from trucoclub.usuarios u where u.dni = documento) then
        raise exception 'DNI_OCUPADO: ya hay una cuenta con ese DNI';
    end if;
    insert into trucoclub.usuarios
        (auth_id, username, email, dni, fecha_registro, partidas_ganadas, saldo, rol, bloqueado)
    values
        (new.id, nombre, new.email, documento, (now() at time zone 'America/Argentina/Buenos_Aires'), 0, 0, 'JUGADOR', false);
    return new;
end;
$$;

drop trigger if exists al_registrarse_crear_perfil on auth.users;
create trigger al_registrarse_crear_perfil
    after insert on auth.users
    for each row execute function trucoclub.crear_perfil_de_usuario();

-- Si el usuario cambia su email en Supabase Auth, se actualiza la copia del perfil
create or replace function trucoclub.sincronizar_email()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    update trucoclub.usuarios set email = new.email where auth_id = new.id;
    return new;
end;
$$;

drop trigger if exists al_cambiar_email on auth.users;
create trigger al_cambiar_email
    after update of email on auth.users
    for each row
    when (old.email is distinct from new.email)
    execute function trucoclub.sincronizar_email();

revoke all on function trucoclub.crear_perfil_de_usuario() from public, anon, authenticated;
revoke all on function trucoclub.sincronizar_email() from public, anon, authenticated;
